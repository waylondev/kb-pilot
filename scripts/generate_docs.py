def generate_markdown_content(title, sections):
    """生成 Markdown 文档内容"""
    lines = [f"# {title}", ""]
    
    for section_title, subsections in sections:
        lines.append(f"## {section_title}")
        lines.append("")
        
        for sub_title, table_data in subsections:
            lines.append(f"### {sub_title}")
            lines.append("")
            
            # 表格头部
            header = table_data[0]
            lines.append("| " + " | ".join(header) + " |")
            lines.append("|" + "|".join(["------"] * len(header)) + "|")
            
            # 表格数据行
            for row in table_data[1:]:
                lines.append("| " + " | ".join(str(c) for c in row) + " |")
            
            lines.append("")
    
    return "\n".join(lines)


def generate_docs():
    """生成所有文档"""
    doc_id_counter = 11  # 从 doc_011 开始（已有 doc_001~010）
    stats = {"domains": 0, "docs": 0}
    
    for domain_dir_name, domain_info in DOMAINS.items():
        domain_name = domain_info["name"]
        domain_path = KB_PATH / domain_dir_name
        domain_path.mkdir(parents=True, exist_ok=True)
        stats["domains"] += 1
        
        for doc_info in domain_info["docs"]:
            doc_title = doc_info["title"]
            doc_id = f"doc_{doc_id_counter:03d}"
            doc_short = _short_name(doc_title)
            doc_dir = domain_path / f"{doc_id}_{doc_short}"
            doc_dir.mkdir(parents=True, exist_ok=True)
            
            # 生成 Markdown
            md_content = generate_markdown_content(doc_title, doc_info["sections"])
            md_filename = f"{doc_title}.md"
            md_path = doc_dir / md_filename
            md_path.write_text(md_content, encoding="utf-8")
            
            # 生成 metadata.yaml
            metadata = f"""doc_id: {doc_id}
title: {doc_title}
domain: {domain_name}
maintainer: auto
source_format: markdown
converted_at: "{TODAY}"
conversion_quality: good
manual_edit: false
"""
            (doc_dir / "metadata.yaml").write_text(metadata, encoding="utf-8")
            
            stats["docs"] += 1
            doc_id_counter += 1
    
    return stats


def _short_name(title):
    """从标题生成目录名，使用完整标题，过滤非法字符"""
    name = title.replace(" ", "_")
    for ch in r'\/:*?"<>|':
        name = name.replace(ch, "_")
    return name


